#   지수 백오프를 그냥 두면 몇 시간까지 벌어진다. 와이파이가 20분 만에 돌아왔는데
#   다음 시도가 3시간 뒤로 예약돼 있으면, 큐는 살아 있었지만 알림은 여전히 늦는다.
#   상한이 "복구되면 늦어도 이 시간 안에는 나간다"를 보장한다.
#   올리면 -> 죽은 네트워크를 덜 두드린다(전력 절약). 내리면 -> 복구를 빨리 따라잡는다.
OUTBOX_BACKOFF_BASE_SEC = 30.0
OUTBOX_BACKOFF_MAX_SEC = 10 * 60.0

# 이 시간을 넘겨 도착한 알림은 '지연됨'으로 표시해서 보낸다.
#
# 왜 필요한가
#   보호자가 "지금 벌어지는 일"과 "와이파이가 끊긴 두 시간 전에 벌어진 일"을 구분할 수
#   있어야 한다. 구분이 없으면 이미 지나간 상황에 대해 지금 놀라게 된다.
OUTBOX_DELAYED_THRESHOLD_SEC = 5 * 60.0

# T2·T3 를 포기하기까지의 시도 횟수.
#
# T1 이 이 목록에 없는 것이 핵심이다. 생명 안전 알림은 시도 횟수로 버리지 않는다.
# 계속 재시도하며(백오프 상한 안에서), 큐에 남아 있는 것 자체가 보호자에게 알려야 할
# 상태다. 반면 어제의 일일 요약은 무한 재시도할 가치가 없다.
OUTBOX_MAX_ATTEMPTS = {
    "T2": 20,
    "T3": 20,
}

# 이 큐를 비우는 틱 주기. 침묵 틱(60초)보다 잦은 이유는, 네트워크가 돌아온 직후
# 밀린 알림을 빨리 흘려보내야 하기 때문이다.
OUTBOX_FLUSH_INTERVAL_SEC = 30

# 한 번의 flush 에서 처리할 최대 건수.
#
# 왜 한 번에 전부 보내지 않는가
#   오래 끊겼다 복구되면 수십 건이 한꺼번에 나가서 보호자 화면을 도배한다. 그리고
#   전송이 느린 채널에서 틱 하나가 오래 붙잡힌다. 나머지는 다음 틱이 가져간다.
OUTBOX_FLUSH_BATCH_SIZE = 10
