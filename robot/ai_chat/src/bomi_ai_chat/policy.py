#   각 행마다 생성 LLM 호출이 하나씩 붙는다(§16). 오래 밀렸다가 한꺼번에
#   수십 건을 처리하면 그 틱 하나가 오래 붙잡히고, 마침 그 순간 침묵 사다리나
#   T3 동의 판정처럼 더 급한 턴이 겹치면 지연 예산을 갉아먹는다.
#   올리면 -> 밀린 큐가 빨리 줄어든다. 내리면 -> 틱 하나의 비용이 낮아진다.
