#   감시 장치가 된다. 그러면 어르신은 다시 털어놓지 않고, T3 자체가 죽는다.
#   올리면 -> 더 안전하지만, 하루가 끝나 물어볼 기회를 놓칠 수 있다.
#   내리면 -> 대화의 여운이 남아 있는 동안 끼어들 위험이 커진다.
