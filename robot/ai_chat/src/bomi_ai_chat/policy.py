# 어르신은 배고픔과 갈증을 잘 느끼지 못해서, 거른 식사와 탈수가 복약 시각보다
# 더 문제인 경우가 많다. 그래서 이 둘은 백엔드 데이터 없이도 돌아가는 기본 루틴이다.
