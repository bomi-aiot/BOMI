# rest_state 가 RESTING 일 때 위 임계치에 곱하는 배수.
#
# 왜 필요한가
#   쉬는 중의 침묵은 정상이다. 사다리를 완전히 멈추고 싶지는 않다(쉬다가 쓰러질 수도
#   있다). 대신 훨씬 인내심 있게 동작해야 한다.
RESTING_PATIENCE_MULTIPLIER = 3.0

# 침묵 틱 주기. 배터리 구동이라 주기가 곧 전력이고, 시간 단위 임계치에 1분 미만의
# 해상도는 아무 이득이 없다.
SILENCE_TICK_INTERVAL_SEC = 60


# ─────────────────────────────────────────────────────────────────────────────
