"""대화 정책 상수 — 로봇의 성격을 결정하는 모든 튜닝 다이얼.

config.py 와 무엇이 다른가  ★ 먼저 읽을 것
    config.py = 환경변수 로딩과 검증. 배포 환경마다 값이 바뀐다(API 키, DB 주소).
    policy.py = 이 파일. 코드 상수. '제품 판단'이 바뀔 때만 바뀐다.

    둘을 합치면 안 된다. 수명이 다르다. 환경변수는 서버를 옮기면 바뀌고,
    정책 상수는 "로봇이 너무 잔소리한다"는 피드백을 받았을 때 바뀐다.

어디에 위치하는가
    게이트, 침묵 사다리, 오디오 계층, 출력 정제가 이 파일을 import 한다.
    여기에는 로직이 없다. 숫자, 집합, 코드 표만 있다.

왜 존재하는가
    이 시스템의 모든 임계치는 "실제 거실에서 로봇이 이상하게 행동하는 걸 보고
    누군가 바꾸고 싶어질 값"이다. 그 숫자가 함수 안에 박혀 있으면, 튜닝은 곧
    로직 수정이 되고, 튜닝할 때마다 동작 버그가 날 위험을 안게 된다.

    그래서 임계치는 여기, 로직은 다른 곳. 리뷰어가 이 파일만 읽고도 로봇의 성격을
    예측할 수 있어야 한다.

이 파일을 읽는 방법
    모든 상수에 "올리면 어떻게 되고 내리면 어떻게 되는지"를 적어두었다.
    새로 추가할 때도 이 규칙을 지킨다. 나중에 이 값을 튜닝하는 사람은 그것을 작성한
    사람이 아니다.

참고
    CLAUDE.md §7 (게이트와 우선순위 행렬), §10 (침묵 사다리), §13 (barge-in)
"""

from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────────
# 우선순위 모델  (CLAUDE.md §7)
#
# 두 개의 표가 서로 다른 일을 한다.
#   PRIORITY_RANK   -> "여러 후보가 게이트를 통과하면 누가 이기는가?"
#   PRIORITY_POLICY -> "이 후보는 어떤 게이트를 무시해도 되는가?"
#
# 앞으로 받게 될 동작 요청("밤에 깨우지 마세요", "인슐린 알림은 무조건 나가야 해요")은
# 거의 전부 이 표의 수정이고, 게이트 로직 수정이 아니다. 그 상태를 유지해야 한다.
# 우선순위 예외 처리가 게이트 루프 안으로 스며드는 순간, 로봇이 무슨 행동을 할지
# 아무도 예측할 수 없게 된다.
# ─────────────────────────────────────────────────────────────────────────────

PRIORITY_RANK = {
    "critical": 6,       # 생존 확인 — 의료 응급 상황일 수 있다
    "high": 5,           # 시간을 지켜야 하는 복약(인슐린 등)
    "event": 4,          # 현관 인사. 늦으면 무의미하므로 일상 항목보다 우선
    "clarification": 3,  # 활성 fact_candidate 의 한 필드 재질의
    "medium": 2,         # 일반 복약, 식사
    "low": 1,            # 수분 권유, 가벼운 안부
    "ambient": 0,        # 잡담
}

# 각 우선순위가 '무시'할 수 있는 게이트. '무시'란 그 게이트가 막으려 해도 통과로
# 처리한다는 뜻이다. 목록에 없는 게이트는 존중한다.
PRIORITY_POLICY = {
    # 응급 가능성은 예의보다 우선한다. 깨워도 되고, TV 소리를 뚫고 말해도 된다.
    "critical": {"quiet_hours", "cooldown", "interruption"},
    # 인슐린은 적당한 때를 기다릴 수 없다. 단 대화 중에는 끼어들지 않는다.
    # 말하고 있다면 의식이 있고 그 자리에 있다는 뜻이니까.
    "high": {"quiet_hours", "cooldown"},
    # 인사: 방금 말했다? 상관없다, 누군가 문을 통과했다.
    # quiet hours 는 특별 처리한다 — 아래 QUIET_TERSE 참고.
    "event": {"cooldown"},
    # 보류된 사실을 다시 묻는 건 침묵보다 유용하지만, 누굴 깨울 만큼 급하지는 않다.
    "clarification": {"cooldown"},
    "medium": set(),
    "low": set(),
    "ambient": set(),
}

# quiet hours 가 '침묵'이 아니라 '짧게 말하기'를 뜻하는 우선순위.
#
# 왜 존재하는가
#   어르신이 새벽 2시에 귀가한다. 아무 말도 안 하면 냉정하고 약간 으스스하다.
#   낮처럼 길게 인사하면 시끄럽다. 그래서 인사는 terse=True 를 달고 게이트를
#   통과하고, response_shaper 가 몇 마디로 깎는다. 게이트에서 결과가 '차단'도
#   '통과'도 아닌 유일한 지점이다.
QUIET_TERSE = {"event"}


# ─────────────────────────────────────────────────────────────────────────────
# 게이트 타이밍
# ─────────────────────────────────────────────────────────────────────────────

# 로봇이 말한 뒤, '일상적인' 알림이 다시 나갈 수 있게 되기까지의 최소 침묵 시간.
#   올리면 -> 차분한 로봇. 대신 알림이 늦게 밀릴 수 있다.
#   내리면 -> 알림은 정시에. 대신 로봇이 잔소리처럼 느껴지기 시작한다.
# critical / high / event / clarification 은 이 게이트를 무시한다(PRIORITY_POLICY).
COOLDOWN_SEC = 8 * 60

# 잡담에 추가로 붙는 쿨다운 배수. 경쟁자가 없을 때도 잡담이 기능적 발화보다
# 드물게 나오도록 한다.
#   올리면 -> 조용한 말벗. 내리면 -> 수다스럽지만 반복적으로 느껴질 위험.
AMBIENT_COOLDOWN_MULTIPLIER = 4.0

# 현관 인사가 유효한 시간.
#
# 왜 이렇게 짧은가
#   문이 열린 지 10분 뒤의 "어서오세요"는 침묵보다 나쁘다. 로봇이 빈 현관에
#   혼자 외치는 상황이 된다. 만료된 인사는 재스케줄이 아니라 폐기한다
#   (CLAUDE.md §11).
#   올리면 -> 복도를 천천히 걸어와도 인사가 나간다.
#   내리면 -> 더 많은 인사가 그냥 사라진다.
GREETING_TTL_SEC = 45


# ─────────────────────────────────────────────────────────────────────────────
# 웨이크워드('보미야') 감지  (audio_io/wakeword.py)
#
# 로봇을 깨우는 상시 청취기의 튜닝 다이얼. 감지는 '최근 WINDOW 프레임 중 MIN_HITS 개
# 이상'이 임계값을 넘으면 성립한다(단발 오탐 억제, recall 유지). 모델 경로/사용여부는
# 배포 환경값이라 config.py 에 있고, 여기에는 '성격'을 정하는 값만 둔다.
# ─────────────────────────────────────────────────────────────────────────────

# 한 프레임을 감지로 칠 점수 문턱값(0~1).
#   올리면 -> 오탐↓("보라야" 같은 유사어를 덜 깨움) 대신 진짜 "보미야"를 더 놓친다.
#   내리면 -> 잘 깨어나지만 유사어·잡음에 더 자주 깬다.
# recall 을 위해 기본 0.5 보다 낮춘 0.4. 단발 오탐(스치는 한 프레임)은 이 값이 아니라
# MIN_HITS=2 가 막는다 — 0.4 + MIN_HITS=1 조합은 단발 오탐이 너무 잦아 종료 후 자동
# 재시작을 유발했다. (한때 0.45 였다는 주석이 남아 있었는데 실값과 어긋난 스테일이었다.)
WAKEWORD_THRESHOLD = 0.4

# 감지 판정에 쓰는 '최근 프레임' 창 크기(1프레임=80ms). WINDOW*80ms 동안을 본다.
#   올리면 -> 튀엄튀엄한 발화도 잘 잡지만, 창이 길어 오탐 여지도 늘어난다.
#   내리면 -> 더 또렷한 연속 발화만 잡는다.
WAKEWORD_WINDOW = 4

# 위 창 안에서 임계값을 넘어야 하는 프레임 수.
#   올리면 -> 오탐↓ 대신 진짜 호출을 놓칠 수 있다(더 또렷하게 불러야 함).
#   내리면 -> 잘 깨어나지만 단발 오탐이 늘어난다. 1이면 '한 프레임만 넘어도 감지'.
# 1은 단발 소음/에코에도 깨어나 종료 후 자동 재시작을 유발했다 -> 2로 되돌린다.
# (진짜 "보미야"는 여러 프레임 연속 높으므로 2로도 잘 잡힌다.)
WAKEWORD_MIN_HITS = 2

# 모델에 한 번에 넣는 오디오 프레임 크기(샘플). openWakeWord 는 16kHz 기준 1280(80ms)
# 배수를 권장한다. 이 값은 모델 규격이라 사실상 고정이다(바꾸지 말 것).
WAKEWORD_FRAME_SAMPLES = 1280


# ─────────────────────────────────────────────────────────────────────────────
# 대화 세션 종료  (pipeline._run_conversation)
#
# "보미야"로 시작된 하나의 '대화'를 언제 끝낼지. 두 가지로 판정한다.
#   1) 무응답: 마지막 '실제 발화' 이후 이 시간이 지나도록 아무 말이 없으면 끝낸다.
#   2) 마무리 언급: 사용자가 그만하겠다는 뜻을 말하면 끝낸다(아래 큐 목록).
# 종료되면 다시 "보미야" 대기로 돌아간다(프로그램 종료가 아니다).
# ─────────────────────────────────────────────────────────────────────────────

# 마지막 '실제 발화' 이후 이 시간(초)을 넘겨 아무 말이 없으면 대화를 끝낸다.
#   올리면 -> 조용해도 더 기다린다(잠깐 생각하는 어르신에게 관대). 대신 빈 대화가 길어진다.
#   내리면 -> 빨리 끝난다. 대신 말이 느린 분의 대화를 성급히 끊을 수 있다.
CONVERSATION_IDLE_TIMEOUT_SEC = 15

# ─────────────────────────────────────────────────────────────────────────────
# 대화(conversation_id) 경계  (S15P11E102-306, CLAUDE.md §6, §12)
#
# 위의 CONVERSATION_IDLE_TIMEOUT_SEC 과 이름이 비슷하지만 완전히 다른 값이다 — 헷갈리기
# 쉬우니 반드시 구분한다.
#   CONVERSATION_IDLE_TIMEOUT_SEC   웨이크워드로 열린 '리슨 세션'을 언제 끊을지(15초).
#                                    pipeline._run_graph_conversation 이 오디오 캡처
#                                    루프를 멈추는 기준이다.
#   CONVERSATION_BOUNDARY_IDLE_SEC  서버의 conversation_id 를 언제까지 '이어 붙일지'
#                                    (아래). graph/ingress.note_interaction 이 쓴다.
#
# 왜 따로 필요한가
#   conversation_id 를 무조건 이어 붙이면 로봇이 켜져 있는 내내 대화가 하나로 무한히
#   커져서 "최근 대화" 문맥 조립이 의미를 잃는다. 반대로 매 턴 새로 열면(306에서 고친
#   버그) 방금 한 말조차 다음 턴에 기억하지 못한다. 그래서 '유휴 시간'이라는 중간
#   기준으로 대화를 끊는다 — 잠깐 말이 끊긴 것과, 자리를 뜨고 한참 뒤에 돌아온 것을
#   가른다.
# ─────────────────────────────────────────────────────────────────────────────

# 이 시간(초)만큼 어르신의 발화가 없었다가 다시 말을 걸면, 이어 붙이지 않고 새
# 대화로 연다.
#   올리면 -> 대화가 더 오래 이어진다. 잠깐 다른 일을 하다 와도 문맥이 유지된다.
#             대신 사실상 무관한 대화 두 덩이가 하나로 묶일 수 있다.
#   내리면 -> "최근 대화"가 더 촘촘하게 쪼개진다. 대신 화장실 다녀오는 정도의 짧은
#             공백에도 대화가 끊겨서, 방금 한 말을 못 알아듣는 것처럼 보일 수 있다.
CONVERSATION_BOUNDARY_IDLE_SEC = 30 * 60

# 사용자가 '대화를 그만하겠다'는 뜻으로 쓰는 표현들. 발화에 이 중 하나라도(공백 무시)
# 들어 있으면 대화를 끝낸다.
#
# 왜 키워드 부분일치인가 (LLM 을 안 쓰는 이유)
#   종료 판정에 생성 LLM 을 또 부르면 턴마다 왕복이 늘어 2초 예산이 무너진다
#   (CLAUDE.md §16). 값싼 부분일치로 시작하고, 정확도가 더 필요하면 나중에 의도
#   분류로 올린다. 완벽하지 않으니 실제 녹취를 보고 목록을 늘려야 한다.
CONVERSATION_FAREWELL_CUES = (
    "그만하자", "그만할래", "그만할게", "그만하고", "그만말", "그만얘기", "그만이야기",
    "여기까지", "이제그만", "이제쉴", "쉬어야", "쉴게", "쉴래", "자러", "잘게",
    "대화끝", "이만", "나중에얘기", "나중에이야기", "다음에얘기", "끝내자", "끝낼래",
    # "이제 됐어"는 필수 시나리오 L 의 종료 문구다(공백 제거 후 부분일치이므로
    # "이제됐어"). "됐어" 단독은 넣지 않는다 — "약 다 먹었어, 됐어" 같은 완료 보고를
    # 종료로 오인한다.
    "이제됐어",
)


# ─────────────────────────────────────────────────────────────────────────────
# 현재 대화 문맥 (자연스러운 대화 Phase 2, CLAUDE.md §30)
#
# "이번 주말에 제주도 가" 다음의 "날씨 어때?"를 제주로 해석하는 계층의 조절값.
# 전부 graph/context_slots.py 만 읽는다.
# ─────────────────────────────────────────────────────────────────────────────

# 문맥 후보의 기본 수명(초). 만료되면 언급이 없어도 사라진다.
#   올리면 -> 오래된 화제가 더 오래 붙는다. 한나절 전의 제주가 저녁 질문을 삼킬 수 있다.
#   내리면 -> 문맥이 빨리 죽어서 방금 한 여행 이야기조차 못 잇는다.
# 2시간: 한 번의 외출·낮잠을 견디되 '오늘의 다른 화제'까지 넘보지 않는 길이. 추정값.
CONTEXT_CANDIDATE_TTL_SEC = 2 * 3600.0

# 이 신뢰도 밑으로 감쇠한 후보는 죽은 것으로 본다.
#   올리면 -> 문맥이 빨리 끊긴다(보수적). 내리면 -> 희미한 문맥도 계속 쓴다.
CONTEXT_MIN_CONFIDENCE = 0.4

# 지역 언급이 없는 평범한 턴 하나가 지날 때마다 곱하는 감쇠 계수.
#   1.0*0.85^2 = 0.72 -> 관련 없는 이야기 대여섯 턴이면 임계(0.4) 밑으로 내려간다.
#   올리면 -> 문맥이 끈질기게 남는다. 내리면 -> 두어 턴 만에 잊는다.
CONTEXT_DECAY_PER_TURN = 0.85

# 화제 전환 표지("그런데")로 시작하는 턴에 곱하는 감쇠 계수. 한 번에 임계 밑으로
# 보내는 것이 목적이다 — 시나리오 E: "그런데 오늘 분리수거 날이야?"는 제주가 아니다.
CONTEXT_TOPIC_SHIFT_DECAY = 0.3

# 앞선 문맥을 가리키는 지시 표현. 이게 있으면 감쇠 대신 '재사용'으로 친다.
# 실제 녹취를 보고 늘린다 — BACKCHANNELS 와 같은 주의사항.
CONTEXT_REFERENCE_TERMS = ("거기", "거긴", "그쪽", "그곳", "근처", "저기")

# 화제 전환의 담화 표지. 문장 '머리'에서만 본다(context_slots._is_topic_shift).
CONTEXT_TOPIC_SHIFT_MARKERS = ("그런데", "근데", "아 참", "참,")

# 정정 표지. "대전 말고 대구" — 표지 '뒤'의 도시가 새 값이다 (시나리오 H).
