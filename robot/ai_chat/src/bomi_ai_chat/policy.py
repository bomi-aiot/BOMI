# 기준점이 바뀌었다 (S15P11E102-253)
#   263 에서는 '정서 발화 한 번'이 이 지연의 시작점이었다. 지금은
#   jobs.ticks.consent_tick 이 T3_CONSENT_SIGNAL_THRESHOLD 를 넘긴 그 순간이
#   시작점이다 — 질문 자체가 즉시 큐잉되지 않으므로(누적을 기다린다), 지연은
#   "마지막 확인 시각"이 아니라 "질문을 올리기로 확정한 시각"부터 잰다.
T3_CONSENT_DELAY_SEC = 45 * 60

