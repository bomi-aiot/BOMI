# 사실 추출 기능 자체의 킬스위치 — 코드 상수.
#
# config.py 의 EXTRACTION_ENABLED 환경변수와 무엇이 다른가  (T3_CONSENT_ENABLED 와
# 같은 구도)
#   이 값은 '제품 판단'이다. 기본이 켜짐인 이유는, 꺼지면 대화에서 아무 기억도
#   자라지 않고(§1 인지 지원 축이 죽는다) 그 사실이 로그 한 줄 없이 조용하기
#   때문이다. config.py 의 환경변수는 '오늘 당장' 끄고 싶을 때 쓰는 운영
#   비상구다 — LLM 비용이 튀거나 백엔드가 사실 후보로 도배될 때, 코드를 고치고
#   재배포할 시간 없이 그날 안에 끌 수 있어야 한다. 둘 중 하나라도 꺼지면
#   memory_write 는 큐잉하지 않고 extraction_flush 도 아무것도 하지 않는다.
EXTRACTION_ENABLED = True

# 이보다 짧은 발화는 큐잉하지 않는다.
#
# 왜 필요한가
#   "네", "아니요", "응", "그래요" 같은 대답에서 뽑을 '기억'은 없다. 이 필터가
#   없으면 큐가 뽑을 것 없는 행으로 가득 차고, extraction_flush 가 매번 LLM 을
#   불러 빈 배열만 돌려받는다 — 비용만 쓰고 아무것도 안 남긴다.
#   올리면 -> 짧은 진짜 정보("손주 옴")도 걸러질 수 있다.
#   내리면 -> 뽑을 것 없는 대답까지 큐에 쌓여 flush 비용이 늘어난다.
EXTRACTION_MIN_UTTERANCE_LENGTH = 6

# 한 번의 flush 에서 처리할 최대 대기 행 수.
