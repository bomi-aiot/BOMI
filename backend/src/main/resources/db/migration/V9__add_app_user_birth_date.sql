-- V9 : app_user 에 생년월일을 추가한다 (S15P11E102-259)
--
-- 로봇 프롬프트는 이미 "나이"·"질환" 두 칸을 찾는데, 서버가 그 값을 안 보내서 조용히
-- 사라지고 있었다. 이 마이그레이션은 원인 중 스키마가 없는 쪽(A)을 고친다. 이름표
-- 오타(B)는 코드만 고치는 별도 수정이라 이 파일과는 무관하다.
-- 참고: CLAUDE.md §8(고정 사실은 정확 조회), §19(DB 작업 항목)

-- 왜 nullable 인가
--   이 마이그레이션 이전에 만들어진 어르신, 그리고 아직 온보딩에서 생년월일을 답하지
--   않은 어르신이 있다. NOT NULL 로 만들면 그 행들에 값을 지어내야 하고, 지어낸
--   생년월일로 계산한 나이는 틀린 나이다. 비어 있으면 대화 문맥의 나이 줄만 빠지고
--   오류는 나지 않는다 — 이 티켓의 완료 조건이 명시적으로 요구하는 동작이다.
--
-- 왜 나이 자체가 아니라 생년월일을 저장하는가
--   나이는 저장하는 순간부터 매일 조금씩 틀려지는 값이다(생일마다 갱신 배치가
--   필요해진다). 생년월일은 변하지 않는 사실이고, 나이는 조회 시점에 계산한다
--   (ConversationContextService.computeAge).
ALTER TABLE app_user
    ADD COLUMN birth_date date;
