-- V11 : 개인차가 있어야 하는 값 세 가지를 app_user 에 채운다 (S15P11E102-261)
--
-- 지금까지 어르신 개개인이 달라야 할 값 세 가지가 모두 같거나 아예 없었다.
--   1. 기상·취침 시각 — 침묵 사다리의 루틴 베이스라인 필터가 쓸 값 자체가 없었다
--      (quiet_hours 는 이미 V2 에서 개인값이다. 헷갈리지 않는다 — 이 마이그레이션은
--      quiet_hours 를 건드리지 않는다).
--   2. 만성 통증 부위 — 로봇 코드에 박힌 고정 목록 14개가 모든 어르신에게 동일하게
--      적용되고 있었다.
--   3. 단골 병원 — 전국 병원 검색은 되지만 "이 어르신이 다니는 곳"이 어디에도 없었다.
-- 참고: CLAUDE.md §8(고정 사실은 정확 조회), §10(침묵 사다리와 루틴 베이스라인),
--       §19(DB 작업 항목) / S15P11E102-261
--
-- 왜 만성 통증 부위·단골 병원이 care_record 가 아니라 app_user 인가
--   care_record 로 보내면 OnboardingMaterializer.java 가 아직 care_record 쓰기
--   경로를 갖지 못한 문제(S15P11E102-258)에 그대로 걸린다. 이 두 값은 그 자체로
--   위험한 의료 판단이 아니라 "본인이 말하는 참고 정보"이므로, app_user 의 단순
--   컬럼으로 두면 이 티켓 하나로 끝낼 수 있다. care_record 로 옮길 필요가 생기면
--   그때 별도 마이그레이션으로 이관한다.
ALTER TABLE app_user
    -- 왜 nullable 인가
    --   이 마이그레이션 이전에 만들어진 어르신, 그리고 아직 온보딩에서 답하지 않은
    --   어르신이 있다. 모르는 값을 지어내 저장하면 안전 판단(루틴 베이스라인)이
    --   거짓 위에서 돌게 된다. 비어 있으면 그 어르신은 지금과 동일하게(개인화 없이)
    --   동작한다 — 이 티켓의 완료 조건이 명시적으로 요구하는 동작이다.
    -- 시간대 주의: quiet_hours 와 마찬가지로 로컬 시각이며 app_user.time_zone 으로
    --   해석한다. UTC 로 저장하지 않는다.
    ADD COLUMN wake_time  time,
    ADD COLUMN sleep_time time,
    -- 자유 문자열로 둔다. 로봇 코드에 박혀 있던 14개 고정 목록을 대체하는 값이므로,
    -- 그 목록보다 넓은 표현(예: "왼쪽 무릎, 허리")을 담을 수 있어야 한다.
    -- 주의: 이 값은 응급 판정(triage)에 절대 쓰지 않는다. "만성"이라는 말 자체가
    -- 새로운 통증 호소를 가리지 않도록, 이 필드는 문맥 조립에만 실리고 티어 판정
    -- 로직은 이 값을 읽지 않는다(로봇 쪽 회귀 테스트가 별도로 고정한다).
    ADD COLUMN chronic_pain_area text,
    -- 단골 병원(및 약국)을 부르는 이름을 자유 문자열로 담는다. 위치·전화번호 같은
    -- 구조화된 값은 이 티켓 범위가 아니다 — "가까운 병원 검색"과 달리 "늘 가시는
    -- 곳의 이름을 말해 줄 수 있는가"만 채운다.
    ADD COLUMN preferred_hospital text;

COMMENT ON COLUMN app_user.wake_time IS
    '어르신의 평소 기상 시각(로컬, time_zone 기준). 침묵 사다리의 루틴 베이스라인이 '
    '읽을 값이며, 이 마이그레이션은 컬럼만 채운다 — 베이스라인 필터 자체는 '
    'S15P11E102-261 범위 밖이다(jobs/ticks.py 참고).';
COMMENT ON COLUMN app_user.sleep_time IS
    '어르신의 평소 취침 시각(로컬, time_zone 기준). wake_time 과 용도가 같다.';
COMMENT ON COLUMN app_user.chronic_pain_area IS
    '어르신이 밝힌 만성 통증 부위(자유 문자열). 응급 판정에는 쓰지 않는다.';
COMMENT ON COLUMN app_user.preferred_hospital IS
    '어르신이 다니는 단골 병원·약국 이름(자유 문자열).';
