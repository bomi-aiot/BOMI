-- V6 : T2 일일 요약이 필요로 하는 컬럼 3개 (S15P11E102-211)
--
-- V4 가 daily_activity_metric 을 만들었지만, 211 의 집계 항목 중 하나를 담을 곳이
-- 없었고 "하루 1회만 발송"을 보장할 표시도 없었다.
--
-- 적용된 마이그레이션은 수정하지 않는다. V4 를 고치지 않고 여기 더한다.

-- ── 1. 지남력 질문 반복 횟수 ────────────────────────────────────────────────
--
-- "오늘 며칠이야?"를 하루에 몇 번 물으셨는가. 반복이 늘어나는 것은 인지 저하 신호다.
--
-- ★ 이 값은 T2 추세로만 간다. 절대 프롬프트에 닿아서는 안 된다.
--   닿으면 어조에 새어나가서 열 번째 답변이 짜증스럽게 들린다. 열 번째 질문도 첫
--   번째와 같은 온기로 답하는 것과, 그 반복을 기록하는 것은 서로 다른 목적지다.
--   둘을 분리할 수 있어서 두 동작이 동시에 가능하다 (CLAUDE.md §8).
--
-- 다른 지표와 같이 NULL 을 허용한다. 모르는 것과 0은 다르다 — 0으로 저장하면
-- "오늘은 한 번도 안 물으셨다"가 되고, 그것은 측정하지 못한 날에 대한 거짓말이다.
ALTER TABLE daily_activity_metric
    ADD COLUMN orientation_question_repeat_count smallint;

-- ── 2. 요약 발송 시각 ───────────────────────────────────────────────────────
--
-- 왜 필요한가
--   배치는 재실행된다. 서버 재시작, 수동 실행, 스케줄러 중복 발동. 발송 여부를
--   기록하지 않으면 보호자가 같은 요약을 두 번 받고, 두 번 받는 알림은 읽히지 않는
--   알림이 된다.
--
--   집계 자체는 (senior_id, metric_date) UNIQUE 로 멱등하지만, '발송'은 별개의
--   부수효과라 따로 표시해야 한다.
ALTER TABLE daily_activity_metric
    ADD COLUMN summary_sent_at timestamptz;

-- ── 3. 지남력 질문 표시 ─────────────────────────────────────────────────────
--
-- 어르신의 이 발화가 지남력 질문이었는가.
--
-- 왜 서버가 판정하지 않고 로봇이 표시하는가
--   로봇은 이미 분류한다(classify_intent). 서버가 본문을 다시 분석하면 같은 판정이
--   두 곳에 생기고, 두 곳은 갈라진다. 그리고 서버가 대화 본문을 분석하기 시작하면
--   그 코드는 곧 다른 목적으로도 쓰인다.
--
-- NULL 을 허용한다. 이 컬럼이 생기기 전의 행과, 판정하지 않는 채널(앱)의 행이 있다.
-- false 로 채우면 "지남력 질문이 아니었다"가 되어 과거를 단정하게 된다.
ALTER TABLE conversation_message
    ADD COLUMN orientation_question boolean;
