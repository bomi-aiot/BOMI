-- V17 : 어르신 자택 주소를 app_user 에 채운다 (S15P11E102-347)
--
-- "오늘 날씨 어때?" 가 영원히 되묻기만 하던 이유가 이 컬럼의 부재다. 로봇의 지역
-- 결정 우선순위(로봇 CLAUDE.md §30)는 마지막 폴백으로 프로필 주소를 읽도록 이미
-- 구현·테스트되어 있는데, 대화 문맥 계약(SeniorProfile)에 주소가 없어 그 폴백이
-- 항상 빈손이었다. 233 실기에서는 조회가 건너뛰어진 채 LLM 이 없는 기온을
-- 지어내는 사고까지 확인됐다 — 조회 근거가 없는 상태는 되묻기 아니면 지어내기
-- 둘 중 하나로만 끝난다.
--
-- 왜 home_latitude/home_longitude(V1)와 별개인가
--   좌표는 근처 병원·약국 지오 검색용 숫자쌍이고, 이 컬럼은 사람이 말하고 듣는
--   문자열("부산광역시 부산진구")이다. 로봇의 날씨 폴백은 문자열에서 도시명을
--   찾는 방식이라(weather.extract_city) 좌표로는 동작하지 않는다. 서로 대체재가
--   아니므로 둘 다 남는다.
--
-- 개인정보 범위
--   시·군·구 수준이면 충분하고 상세 번지는 필요 없다 — 소비처(날씨 지역 결정)가
--   도시명만 쓴다. 절단은 저장 시점에 강제하지 않고 수집(온보딩 질문) 쪽 안내
--   문구가 담당한다. 이 값은 로봇 대화 문맥 채널로만 나가고 가디언웹
--   ElderProfileDto 에는 노출하지 않는다.
--
-- 참고: CLAUDE.md §8(고정 사실은 정확 조회), §19 / 로봇 CLAUDE.md §30 / S15P11E102-347
ALTER TABLE app_user
    -- 왜 nullable 인가
    --   이 마이그레이션 이전에 만들어진 어르신, 그리고 아직 주소를 밝히지 않은
    --   어르신이 있다. 모르는 값을 지어내 저장하면 로봇이 엉뚱한 도시의 날씨를
    --   확신 있게 말하게 된다. 비어 있으면 지금과 동일하게(지역을 되물으며)
    --   동작한다 — 티켓 완료 조건이 명시적으로 요구하는 동작이다.
    ADD COLUMN home_address text;

COMMENT ON COLUMN app_user.home_address IS
    '어르신 자택 주소(자유 문자열, 시·군·구 수준 권장). 날씨 기본 지역 등 대화 문맥의 '
    '기본값으로 쓴다. 지오 검색용 좌표(home_latitude/longitude)와 별개이며, 모르면 null이다.';
